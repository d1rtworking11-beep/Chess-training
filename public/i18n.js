const STORAGE_KEY = 'openchess.language';
const supported = code => typeof code === 'string' && Object.hasOwn(STRINGS, code);
// A #ru or #en link wins, then the viewer's saved choice, then the browser's languages.
function detect() {
  const hash = globalThis.location?.hash?.slice(1);
  if (supported(hash)) return hash;
  try { const saved = globalThis.localStorage?.getItem(STORAGE_KEY); if (supported(saved)) return saved; } catch {}
  const preferred = globalThis.navigator?.languages ?? [globalThis.navigator?.language];
  return preferred.some(code => /^ru\b/i.test(code ?? '')) ? 'ru' : 'en';
}
let language = detect();

export const getLanguage = () => language;
export const locale = () => (language === 'ru' ? 'ru-RU' : 'en-US');
export function setLanguage(code) {
  if (!supported(code)) return false;
  language = code;
  try { globalThis.localStorage?.setItem(STORAGE_KEY, code); } catch {}
  return true;
}
export function t(key, params = {}) {
  const value = STRINGS[language][key] ?? STRINGS.en[key];
  if (value === undefined) return key;
  if (typeof value === 'function') return value(params);
  return value.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''));
}
export const decimal = (value, digits) => new Intl.NumberFormat(locale(), {minimumFractionDigits: digits, maximumFractionDigits: digits}).format(value);
export function applyStatic(root = document) {
  document.documentElement.lang = language;
  document.title = t('page.title');
  for (const element of root.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n);
  for (const element of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of element.dataset.i18nAttr.split(';')) { const [attribute, key] = pair.split(':'); element.setAttribute(attribute, t(key)); }
  }
}
